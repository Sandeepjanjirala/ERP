"""Shared building blocks for EduNexa's PDFs (report cards, fee receipts), drawn with ReportLab.

A PDF belongs to the school, so its name heads the page; the footer says it was generated by
EduNexa (docs/DESIGN.md, the one-name rule). ReportLab paragraphs read a little markup, so every
value from the database goes through escape() before it is put in one.
"""

from io import BytesIO
from xml.sax.saxutils import escape

from django.conf import settings
from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

INDIGO = colors.HexColor("#4f46e5")
SLATE = colors.HexColor("#475569")
GRID = colors.HexColor("#e2e8f0")

__all__ = ["Paragraph", "Spacer", "escape", "mm", "render", "styles", "table", "letterhead"]


def styles():
    sheet = getSampleStyleSheet()
    sheet["Title"].textColor = INDIGO
    return sheet


def table(rows, widths):
    """A plain table; the first row is a header. Cells are text, never markup."""
    result = Table(rows, colWidths=widths, repeatRows=1)
    result.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("TEXTCOLOR", (0, 0), (-1, 0), SLATE),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("LINEBELOW", (0, 0), (-1, -1), 0.5, GRID),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    return result


def letterhead(school, subtitle):
    """The school's name and a subtitle (branch and document name), escaped."""
    sheet = styles()
    return [
        Paragraph(escape(school), sheet["Title"]),
        Paragraph(escape(subtitle), sheet["Heading3"]),
        Spacer(1, 4 * mm),
    ]


def render(story, title, author):
    """Build an A4 PDF with EduNexa's footer on every page; returns the bytes."""
    brand = settings.BRAND["name"]
    generated = f"Generated by {brand} on {timezone.localdate():%d %b %Y}"

    def footer(canvas, document):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(SLATE)
        canvas.drawString(document.leftMargin, 10 * mm, generated)
        canvas.drawRightString(A4[0] - document.rightMargin, 10 * mm, f"Page {document.page}")
        canvas.restoreState()

    buffer = BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        title=title,
        author=author,
        creator=brand,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
    )
    document.build(story, onFirstPage=footer, onLaterPages=footer)
    return buffer.getvalue()
