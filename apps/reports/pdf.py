"""The report card PDF, drawn with ReportLab.

The school's name heads the page, because it is the school's document; the footer says it was
generated by EduNexa (docs/DESIGN.md, the one-name rule).
"""

from io import BytesIO
from xml.sax.saxutils import escape

from django.conf import settings
from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from apps.organization.models import Organization

INDIGO = colors.HexColor("#4f46e5")
SLATE = colors.HexColor("#475569")
GRID = colors.HexColor("#e2e8f0")


def result_rows(marks):
    """The results table: a header row, then one row per published mark."""
    rows = [["Subject", "Assessment", "Date", "Score", "Maximum", "Result"]]
    for mark in marks:
        rows.append(
            [
                mark.exam.subject.name,
                mark.exam.title,
                f"{mark.exam.date:%d %b %Y}",
                "Absent" if mark.absent else str(mark.score),
                str(mark.exam.max_marks),
                "Pass" if mark.passed else "Below pass mark",
            ]
        )
    return rows


def _table(rows, widths):
    table = Table(rows, colWidths=widths, repeatRows=1)
    table.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("TEXTCOLOR", (0, 0), (-1, 0), SLATE),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("LINEBELOW", (0, 0), (-1, -1), 0.5, GRID),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    return table


def render_report_card(student, report, school_name):
    """The report card for one student and one year, as PDF bytes.

    `report` is reports.selectors.student_report(): only published results are in it.
    """
    styles = getSampleStyleSheet()
    styles["Title"].textColor = INDIGO
    brand = settings.BRAND["name"]
    year = report["selected_year"]
    classes = ", ".join(f"{e.classroom.grade}-{e.classroom.section}" for e in report["enrollments"])
    summary, attendance = report["summary"], report["attendance_summary"]

    story = [
        # Paragraph reads a little markup, so every value from the database is escaped.
        Paragraph(escape(school_name), styles["Title"]),
        Paragraph(
            escape(f"{student.user.branch.name} · Student progress report"), styles["Heading3"]
        ),
        Spacer(1, 4 * mm),
        _table(
            [
                ["Student", student.user.display_name],
                ["Admission number", student.admission_number],
                ["Class", classes or "-"],
                ["Academic year", year.name if year else "-"],
            ],
            [45 * mm, 125 * mm],
        ),
        Spacer(1, 6 * mm),
        Paragraph("Published results", styles["Heading2"]),
        _table(
            result_rows(report["marks"]),
            [32 * mm, 38 * mm, 24 * mm, 18 * mm, 20 * mm, 38 * mm],
        ),
        Spacer(1, 3 * mm),
        Paragraph(
            escape(
                f"{summary['passed']} of {summary['count']} assessments passed. "
                f"Overall {summary['percentage'] if summary['percentage'] is not None else '-'}%."
            ),
            styles["BodyText"],
        ),
        Spacer(1, 6 * mm),
        Paragraph("Attendance", styles["Heading2"]),
        _table(
            [
                ["Present", "Late", "Absent", "Excused", "Attendance rate"],
                [
                    attendance["P"],
                    attendance["L"],
                    attendance["A"],
                    attendance["E"],
                    f"{attendance['rate']}%" if attendance["rate"] is not None else "-",
                ],
            ],
            [30 * mm, 30 * mm, 30 * mm, 30 * mm, 50 * mm],
        ),
    ]
    if attendance["below_minimum"]:
        story += [
            Spacer(1, 3 * mm),
            Paragraph(
                "<b>Attendance is below 75%.</b> Please speak to the class teacher.",
                styles["BodyText"],
            ),
        ]

    generated = f"Generated by {brand} on {timezone.localdate():%d %b %Y}"

    def footer(canvas, document):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(SLATE)
        canvas.drawString(document.leftMargin, 10 * mm, generated)
        canvas.drawRightString(A4[0] - document.rightMargin, 10 * mm, f"Page {document.page}")
        canvas.restoreState()

    buffer = BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        title=f"Report card: {student.user.display_name}",
        author=school_name,
        creator=brand,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
    )
    document.build(story, onFirstPage=footer, onLaterPages=footer)
    return buffer.getvalue()


def report_card_filename(student, report):
    year = report["selected_year"]
    suffix = f"-{year.starts_on:%Y}" if year else ""
    return f"report-card-{student.admission_number}{suffix}.pdf"


def school_name():
    """The school group's name for the letterhead, or the default before setup."""
    organization = Organization.objects.filter(pk=1).first()
    return organization.name if organization else Organization().name
