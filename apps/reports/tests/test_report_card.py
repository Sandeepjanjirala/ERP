"""The report card PDF: published results only, scoped like the report page, school-branded."""

import base64
import re
import zlib
from datetime import timedelta

from django.urls import reverse

from apps.attendance.services import save_register
from apps.core.testing import ApiTestCase, SchoolTestCase


def pdf_text(content):
    """The text drawn on the pages. ReportLab writes each page's drawing commands compressed
    (zlib) and then as ASCII85 text, so both are undone here."""
    streams = re.findall(rb"stream\r?\n(.*?)endstream", content, re.S)
    text = b""
    for stream in streams:
        try:
            text += zlib.decompress(base64.a85decode(stream.strip(), adobe=True))
        except (ValueError, zlib.error):
            continue  # fonts and other binary streams
    # A line may be drawn as several runs, "(Sri <) Tj (Vidya) Tj": join them up.
    return text.decode("latin-1").replace(") Tj (", "")


class ReportCardTests(SchoolTestCase):
    def download(self, user, student):
        self.client.force_login(user)
        return self.client.get(reverse("report_card", args=[student.pk]))

    def test_parent_downloads_their_childs_card(self):
        self.publish()  # Midterm published; the science test is still a draft
        response = self.download(self.parent, self.e1.student)
        self.assertEqual(response["Content-Type"], "application/pdf")
        self.assertEqual(
            response["Content-Disposition"],
            f'attachment; filename="report-card-ALICE-{self.year.starts_on:%Y}.pdf"',
        )
        self.assertTrue(response.content.startswith(b"%PDF"))
        text = pdf_text(response.content)
        self.assertIn("Test Organisation", text)  # the school's letterhead
        self.assertIn("Generated by EduNexa", text)
        self.assertIn("Midterm", text)
        self.assertNotIn("Science test", text)  # drafts never appear

    def test_scope_matches_the_report_page(self):
        cases = [
            (self.parent, self.e2.student, 404),  # a classmate
            (self.e1.student.user, self.e2.student, 404),
            (self.foreign_teacher, self.e1.student, 404),
            (self.teacher, self.e1.student, 200),
            (self.e1.student.user, self.e1.student, 200),
        ]
        for user, student, status in cases:
            with self.subTest(user=user.username, student=student.admission_number):
                self.assertEqual(self.download(user, student).status_code, status)

    def test_names_are_printed_as_text_not_markup(self):
        self.org.name = "Sri <Vidya> & Sons"
        self.org.save()
        text = pdf_text(self.download(self.admin, self.e1.student).content)
        self.assertIn("Sri <Vidya> & Sons", text)

    def test_low_attendance_is_flagged(self):
        for days_ago in (1, 2, 3):
            save_register(
                self.teacher,
                self.c,
                self.today - timedelta(days=days_ago),
                {self.e1.pk: "A", self.e2.pk: "P"},
                0,
            )
        self.client.force_login(self.parent)
        alice = self.client.get(reverse("student_report", args=[self.e1.student.pk]))
        self.assertContains(alice, "Attendance is below 75%")
        alice_card = pdf_text(self.download(self.parent, self.e1.student).content)
        self.assertIn("Attendance is below 75%", alice_card)
        # Bob was present every day: no warning.
        self.client.force_login(self.teacher)
        bob = self.client.get(reverse("student_report", args=[self.e2.student.pk]))
        self.assertNotContains(bob, "Attendance is below 75%")


class ReportCardApiTests(ApiTestCase):
    def test_api_download(self):
        self.as_user(self.parent)
        url = f"/api/v1/students/{self.e1.student.pk}/report-card/"
        response = self.client.get(url, HTTP_ACCEPT="application/pdf")
        self.assertEqual(response.status_code, 200)
        self.assertTrue(response.content.startswith(b"%PDF"))
        other = self.client.get(
            f"/api/v1/students/{self.e2.student.pk}/report-card/", HTTP_ACCEPT="application/pdf"
        )
        self.assertEqual(other.status_code, 404)
        self.client.force_authenticate(None)
        self.assertEqual(self.client.get(url).status_code, 401)
